// strings
const myVariable = "Mathematics";

// length property
console.log(myVariable.length)
console.log("Mathematics X".length)

// character at position
console.log(myVariable.charAt(2))

// position of character
console.log(myVariable.indexOf("at"))
console.log(myVariable.lastIndexOf("at"))

// slice method
console.log(myVariable.slice(0,10))
console.log(myVariable.slice(5))

// upper case and lower case method
console.log(myVariable.toUpperCase())
console.log(myVariable.toLowerCase())

// includes method
console.log(myVariable.includes("boi"))
console.log(myVariable.includes("th"))

// split method
console.log("Mathematics".split("at"))
console.log(myVariable.split(""))
console.log("Sahil, Sayam, Ishaan".split(","))

